// Deploys MediaRegistry to the local Hardhat node and admits the demo
// consortium. Usage (two terminals):
//   npx hardhat node
//   npx hardhat run scripts/deploy.js --network localhost
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

async function main() {
  const signers = await hre.ethers.getSigners();
  const [pressCouncil] = signers;

  const registry = await hre.ethers.deployContract("MediaRegistry", [], pressCouncil);
  await registry.waitForDeployment();
  const address = await registry.getAddress();
  console.log(`MediaRegistry deployed to ${address} by the Press Council ${pressCouncil.address}`);

  const consortium = [
    [signers[1], "registerPublisher", "The Daily Ledger"],
    [signers[2], "registerPublisher", "Metro News Network"],
    [signers[3], "registerPublisher", "Campus Times"],
    [signers[4], "registerFactChecker", "Northbridge Fact-Check Desk"],
  ];
  for (const [signer, method, name] of consortium) {
    await (await registry[method](signer.address, name)).wait();
    console.log(`  admitted ${name.padEnd(30)} ${signer.address}`);
  }

  const { chainId } = await hre.ethers.provider.getNetwork();
  const out = path.join(__dirname, "..", "..", "frontend", "js", "local-deployment.js");
  fs.writeFileSync(
    out,
    `// AUTO-GENERATED by blockchain/scripts/deploy.js\nwindow.LOCAL_DEPLOYMENT = ${JSON.stringify({ address, chainId: Number(chainId) })};\n`
  );
  console.log(`Wrote ${path.relative(process.cwd(), out)} - open the web app and choose "Local Hardhat".`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
